    detectByIP() {
      // 已有用户明确选择，不再用 IP 干预
      let saved = null;
      try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) {}
      if (saved) return Promise.resolve(null);

      const urls = [
        'https://ipwho.is/',
        'https://ipapi.co/json/'
      ];
      const tryUrl = (url) => {
        return fetch(url, { mode: 'cors' }).then(r => (r.ok ? r.json() : null)).catch(() => null);
      };
      const seq = urls.reduce((p, u) => p.then(m => m || tryUrl(u)), Promise.resolve(null));

      return Promise.race([
        seq,
        new Promise(res => setTimeout(() => res(null), 4000))
      ]).then((data) => {
        if (!data) return null;
        const code = (data.country_code || data.alpha2 || data.country || '').toUpperCase();
        return this.COUNTRY_LANG[code] || null;
      });
    },

    setLang(lang, persist = true) {
      if (!TRANSLATIONS[lang]) lang = DEFAULT_LANG;
      this.current = lang;
      const htmlLang = { zh: 'zh-CN', en: 'en', ja: 'ja', ko: 'ko', fr: 'fr', de: 'de', es: 'es', ru: 'ru', pt: 'pt', it: 'it' };
      document.documentElement.lang = htmlLang[lang] || 'en';
      if (persist) { try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* localStorage 不可用时静默跳过 */ } }
      this.apply();
      this.updateSelector();
      const loginModal = document.getElementById('apex-login-modal');
      if (loginModal) loginModal.remove();
      document.dispatchEvent(new CustomEvent('apexon:langchange', { detail: { lang } }));
    },

    t(key, fallback) {
      const value = TRANSLATIONS[this.current]?.[key];
      return value !== undefined ? value : (fallback !== undefined ? fallback : key);
    },

    getDateLocale() {
      const map = { zh: 'zh-CN', en: 'en-US', ja: 'ja-JP', ko: 'ko-KR', fr: 'fr-FR', de: 'de-DE', es: 'es-ES', ru: 'ru-RU', pt: 'pt-BR', it: 'it-IT' };
      return map[this.current] || 'en-US';
    },

    apply() {
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const text = this.t(key);
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          if (el.placeholder) el.placeholder = text;
        } else if (el.title && el.childNodes.length && el.childNodes[0].nodeType === Node.TEXT_NODE) {
          el.childNodes[0].textContent = text;
        } else {
          el.textContent = text;
        }
      });

      document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
      });

      document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = this.t(el.getAttribute('data-i18n-title'));
      });

      document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        el.setAttribute('aria-label', this.t(el.getAttribute('data-i18n-aria-label')));
      });

      const titleEl = document.querySelector('title[data-i18n]');
      if (titleEl) document.title = this.t(titleEl.getAttribute('data-i18n'));
    },

    injectSelector() {
      if (document.getElementById('apexon-lang-selector')) return;

      const wrapper = document.createElement('div');
      wrapper.id = 'apexon-lang-selector';
      wrapper.className = 'apexon-lang-selector';

      const current = LANGUAGES.find(l => l.code === this.current) || LANGUAGES[0];
      const currentFlag = FLAGS[current.flagKey] || '';

      wrapper.innerHTML = `
        <button class="apexon-lang-selector__btn" aria-haspopup="true" aria-expanded="false" aria-label="${this.t('langSelector')}">
          <span class="apexon-lang-selector__flag">${currentFlag}</span>
          <span class="apexon-lang-selector__name">${current.name}</span>
          <span class="apexon-lang-selector__arrow">▾</span>
        </button>
        <div class="apexon-lang-selector__dropdown" role="menu">
          ${LANGUAGES.map(l => `
            <button class="apexon-lang-selector__item" data-lang="${l.code}" role="menuitem">
              <span class="apexon-lang-selector__flag">${FLAGS[l.flagKey] || ''}</span>
              <span class="apexon-lang-selector__name">${l.name}</span>
            </button>
          `).join('')}
        </div>
      `;

      const btn = wrapper.querySelector('.apexon-lang-selector__btn');
      const dropdown = wrapper.querySelector('.apexon-lang-selector__dropdown');

      btn.addEventListener('click', (e) => {
        e.stopPropagation();
        const expanded = dropdown.classList.toggle('is-open');
        btn.setAttribute('aria-expanded', expanded);
        if (expanded) {
          // 互斥：打开语言面板时关闭其余顶栏设置面板
          document.querySelectorAll('.apex-style-panel.is-open').forEach(p => p.classList.remove('is-open'));
          const pp = document.querySelector('.apex-palette-panel');
          if (pp) pp.setAttribute('hidden', '');
          const ud = document.getElementById('apexUserDropdown');
          if (ud) ud.classList.remove('show');
          const hd = document.getElementById('headerDropdown');
          if (hd) hd.classList.remove('open');
        }
      });

      document.addEventListener('click', () => {
        dropdown.classList.remove('is-open');
        btn.setAttribute('aria-expanded', 'false');
      });

      wrapper.querySelectorAll('.apexon-lang-selector__item').forEach(item => {
        item.addEventListener('click', (e) => {
          e.stopPropagation();
          this.setLang(item.getAttribute('data-lang'));
        });
      });

      const actions = document.querySelector('.header-actions');
      const left = document.querySelector('.apexon-header-left');
      if (actions) {
        actions.appendChild(wrapper);
      } else if (left) {
        const logo = left.querySelector('.apexon-header-logo');
        if (logo && logo.nextSibling) {
          left.insertBefore(wrapper, logo.nextSibling);
        } else {
          left.appendChild(wrapper);
        }
      } else {
        document.body.insertBefore(wrapper, document.body.firstChild);
      }
    },

    updateSelector() {
      const wrapper = document.getElementById('apexon-lang-selector');
      if (!wrapper) return;
      const current = LANGUAGES.find(l => l.code === this.current) || LANGUAGES[0];
      const btn = wrapper.querySelector('.apexon-lang-selector__btn');
      btn.querySelector('.apexon-lang-selector__flag').innerHTML = FLAGS[current.flagKey] || '';
      btn.querySelector('.apexon-lang-selector__name').textContent = current.name;
      btn.setAttribute('aria-label', this.t('langSelector'));
      const dropdown = wrapper.querySelector('.apexon-lang-selector__dropdown');
      dropdown.classList.remove('is-open');
      btn.setAttribute('aria-expanded', 'false');
    }
